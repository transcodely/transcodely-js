// Ingest rules — watch a bucket, transcode what lands in it.
//
// An ingest rule is a standing instruction attached to one storage origin:
// "when an object matching these filters appears, create this job for it".
// Your storage provider posts an event to the rule's endpoint, we record it,
// and a matching event becomes a job with no server of yours in the path.
//
// The endpoint accepts the event shapes the major providers already emit —
// Amazon S3 via SNS, Google Cloud Storage via a Pub/Sub push subscription,
// Supabase Storage via a database webhook, and a generic shape for everything
// else (a Cloudflare R2 queue consumer, for instance). See
// docs/features/ingest-rules.md for the per-provider setup.
//
// Every source delivers at least once, and some deliver the same object twice
// on purpose. Duplicate deliveries are absorbed: an object is identified by
// (rule, bucket, key, etag) and produces exactly one job.

