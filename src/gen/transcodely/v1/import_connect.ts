// Bulk import — bring a whole video library in with one request.
//
// An import is a list of source URLs, each of which becomes a hosted video
// through the same path as VideoService.CreateFromUrl: the same SSRF checks,
// the same admission probe, the same hosted ABR ladder, the same pricing.
//
// The lifecycle is:
//
//   1. Create (status `draft`) with up to 1,000 items, and AddItems to append
//      more, up to 10,000 per import. Nothing is fetched or encoded yet. Every
//      Create and AddItems returns a quote: how many items will be imported,
//      the source minutes we know about, the estimated encode cost and the
//      estimated monthly storage cost.
//   2. Start with a spend cap (`max_spend_eur`, status `running`). Items are
//      dispatched in submission order at a bounded rate that leaves room in
//      your queue for your own uploads.
//   3. If the next item would take the import over its cap, the import pauses
//      (`paused`, pause_reason `spend_cap_reached`). Nothing is lost: raising
//      the cap with Update resumes it.
//   4. When every item has succeeded, failed or been skipped, the import is
//      `completed` and the `import.completed` webhook fires once.
//
// Re-running an import is safe: an item whose `external_id` is already held by
// another item of the same app that is pending, running or succeeded is
// recorded as `skipped` and creates no video. Items that failed or were
// canceled do not hold their external_id, so submitting the same list again
// retries exactly those.

